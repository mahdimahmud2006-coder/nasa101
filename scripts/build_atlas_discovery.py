"""Snapshot public NASA catalog matches for the Atlas comparison tools."""

import json
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timedelta, timezone
from io import BytesIO
from math import floor
from pathlib import Path
from urllib.parse import urlencode
from urllib.request import urlopen

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
CMR = 'https://cmr.earthdata.nasa.gov/search/granules.json'
GIBS = 'https://gibs.earthdata.nasa.gov/wmts/epsg4326/best'
PRODUCTS = {
    'Bangladesh': ('C2949811996-POCLOUD', 'OPERA_L3_Dynamic_Surface_Water_Extent-Sentinel-1'),
    'Nepal': ('C2746980408-LPCLOUD', 'OPERA_L3_DIST-ALERT-HLS_Color_Index'),
}
WINDOW = timedelta(hours=48)
PAGE_SIZE = 500


def utc(timestamp):
    return datetime.fromisoformat(timestamp.replace('Z', '+00:00'))


def visible_browse_tile(layer, lon, lat, date):
    # EPSG:4326 matrix 10 has 1,280 columns of 512 pixels, spanning 360 degrees.
    x, y = (lon+180)/(360/1280), (90-lat)/(360/1280)
    url = f'{GIBS}/{layer}/default/{date}/31.25m/10/{floor(y)}/{floor(x)}.png'
    try:
        with urlopen(url, timeout=12) as response:
            payload = response.read()
        with Image.open(BytesIO(payload)) as tile:
            if tile.size != (512, 512):
                raise ValueError('Unexpected tile dimensions')
            px, py = int((x % 1)*512), int((y % 1)*512)
            near = (max(0, px-20), max(0, py-20), min(512, px+20), min(512, py+20))
            return tile.convert('RGBA').getchannel('A').crop(near).getbbox() is not None
    except (OSError, ValueError) as error:
        print(f'Browse unchecked for {date} at {lon:.6f},{lat:.6f}: {error}')
        return None


def snapshot_case(case):
    dates = [visit['timestamp'] for visit in case['observations']]
    west, south, east, north = case['grid']['bounds_wgs84']
    lon, lat = (west+east)/2, (south+north)/2
    point = f'{lon:.6f},{lat:.6f}'
    collection, layer = PRODUCTS[case['country']]
    temporal = (utc(min(dates))-WINDOW, utc(max(dates))+WINDOW)
    query = CMR + '?' + urlencode({
        'collection_concept_id': collection,
        'point': point,
        'temporal': ','.join(t.isoformat().replace('+00:00', 'Z') for t in temporal),
        'page_size': PAGE_SIZE,
    })
    with urlopen(query, timeout=25) as response:
        entries = json.load(response)['feed']['entry']
        if len(entries) != int(response.headers['CMR-Hits']):
            raise ValueError(f'Incomplete catalog response for {case["case"]}')
    granules = [(utc(item['time_start']), item['id']) for item in entries]
    matches = {}
    for date in dates:
        anchor = utc(date)
        candidates = [item for item in granules if abs(item[0]-anchor) <= WINDOW]
        if candidates:
            observed, concept = min(candidates, key=lambda item: (abs(item[0]-anchor), *item))
            matches[date] = [concept, observed.isoformat().replace('+00:00', 'Z')]
    days = sorted({hit[1][:10] for hit in matches.values()})
    with ThreadPoolExecutor(max_workers=4) as pool:
        visible = dict(zip(days, pool.map(lambda day: visible_browse_tile(layer, lon, lat, day), days), strict=True))
    for hit in matches.values():
        hit.append(visible[hit[1][:10]])
    return {'query': query, 'matches': matches}


def main():
    web = ROOT/'web'
    records = json.loads((web/'atlas-record.json').read_text())
    cases = {name: snapshot_case(case) for name, case in records.items()}
    snapshot = {'checkedUtc': datetime.now(timezone.utc).isoformat(timespec='seconds'),
                'windowHours': WINDOW // timedelta(hours=1),
                'browseMethod': 'NASA GIBS daily overlay, EPSG:4326 matrix 10, alpha in a 40 px square at the study center.',
                'cases': cases}
    target = web/'atlas-discovery-catalog.mjs'
    target.write_text('// Generated by scripts/build_atlas_discovery.py. NASA CMR metadata only.\n'
                      'export const atlasDiscoveryCatalog = ' + json.dumps(snapshot, indent=2) + ';\n')
    for name, case in cases.items():
        visible = sum(hit[2] is True for hit in case['matches'].values())
        print(f'{name}: {len(case["matches"])}/{len(records[name]["observations"])} catalog matches, {visible} with visible browse tiles')


if __name__ == '__main__':
    main()
